import numpy as np
import matplotlib.pyplot as plt
from sklearn.datasets import make_blobs
from sklearn.svm import SVC

# 1. Sinh 24 điểm, hai lớp tách được hoàn toàn
X, y = make_blobs(n_samples=24, centers=[(2.5, 2), (6, 6)],
                  cluster_std=0.9, random_state=7)

# 2. SVM tuyến tính, C rất lớn ~ lề cứng
mo_hinh = SVC(kernel="linear", C=1e6).fit(X, y)
w = mo_hinh.coef_[0]
b = mo_hinh.intercept_[0]
le_rong = 2 / np.linalg.norm(w)
vth = mo_hinh.support_vectors_

print(f"Đường ranh giới: {w[0]:.3f}*x1 + {w[1]:.3f}*x2 + {b:.3f} = 0")
print(f"Độ rộng lề 2/||w|| = {le_rong:.3f}")
print(f"Số vectơ hỗ trợ: {len(vth)} (mỗi lớp: {mo_hinh.n_support_})")
print("Vectơ hỗ trợ:\n", np.round(vth, 3))

x1 = np.linspace(X[:, 0].min() - 1, X[:, 0].max() + 1, 100)
ylim = (X[:, 1].min() - 1, X[:, 1].max() + 1)

def ve_diem(ax):
    ax.scatter(*X[y == 0].T, c="#08306b", s=25, label="Lớp 0")
    ax.scatter(*X[y == 1].T, c="#cb181d", marker="^", s=25, label="Lớp 1")
    ax.set_xlabel("$x_1$"); ax.set_ylabel("$x_2$")
    ax.set_xlim(x1.min(), x1.max()); ax.set_ylim(*ylim)

# Hình 1: ba đường tách đúng bất kỳ
fig, ax = plt.subplots(figsize=(6, 4.5))
ve_diem(ax)
m = (X[y == 0].mean(axis=0) + X[y == 1].mean(axis=0)) / 2
for ten, he_so, mau in [("A", -0.35, "#d95f02"), ("B", -1.8, "#1b7f8c"),
                        ("C", -w[0] / w[1], "k")]:
    ax.plot(x1, m[1] + he_so * (x1 - m[0]), c=mau, label=f"Đường {ten}")
ax.set_title("Cả ba đường đều tách đúng hết")
ax.legend(); plt.show()

# Hình 2: đường SVM, lề và vectơ hỗ trợ
fig, ax = plt.subplots(figsize=(6, 4.5))
ve_diem(ax)
ax.scatter(*vth.T, s=160, facecolors="none", edgecolors="k",
           linewidths=1.5, label="Vectơ hỗ trợ")
for muc, kieu, nhan in [(0, "-", "Ranh giới"), (1, "--", "Lề"), (-1, "--", None)]:
    ax.plot(x1, (muc - b - w[0] * x1) / w[1], "k" + kieu, lw=1.2, label=nhan)
ax.set_title(f"SVM tuyến tính: lề rộng {le_rong:.2f}")
ax.legend(); plt.show()

import numpy as np
from sklearn.datasets import make_blobs
from sklearn.svm import SVC

# 24 điểm, hai cụm tách hẳn nhau
X, y = make_blobs(n_samples=24, centers=[[2, 2], [6, 6]],
                  cluster_std=0.9, random_state=0)
y = 1 - y  # lớp 1 là cụm dưới bên trái, giống hình trên slide

# C rất lớn nghĩa là không cho điểm nào nằm trong lề
svm = SVC(kernel="linear", C=1000)
svm.fit(X, y)

w = svm.coef_[0]
b = svm.intercept_[0]
print(f"w1 = {w[0]:.3f}, w2 = {w[1]:.3f}, b = {b:.3f}")
do_dai_w = np.sqrt(w[0] ** 2 + w[1] ** 2)
print(f"Do rong cua le = 2 / {do_dai_w:.4f} = {2 / do_dai_w:.4f}")
print()

# Các vectơ hỗ trợ nằm đúng trên hai mép lề, nơi f(x) bằng 1 hoặc -1
print("So vecto ho tro:", len(svm.support_))
for i in svm.support_:
    f = svm.decision_function(X[i:i + 1])[0]
    print(f"  diem {i:2d}: x1 = {X[i, 0]:.2f}, x2 = {X[i, 1]:.2f},"
          f" lop {y[i]}, f(x) = {f:+.3f}")
print()

# Những điểm khác nằm ngoài lề, nên |f(x)| lớn hơn 1
f_tat_ca = svm.decision_function(X)
ngoai = np.setdiff1d(np.arange(len(X)), svm.support_)
nho_nhat = np.abs(f_tat_ca[ngoai]).min()
print(f"|f(x)| nho nhat cua cac diem khac: {nho_nhat:.3f}")
print()

# Học lại chỉ với các vectơ hỗ trợ
chi_sv = SVC(kernel="linear", C=1000)
chi_sv.fit(X[svm.support_], y[svm.support_])
w2 = chi_sv.coef_[0]
print("Hoc lai chi voi vecto ho tro:")
b2 = chi_sv.intercept_[0]
print(f"  w1 = {w2[0]:.3f}, w2 = {w2[1]:.3f}, b = {b2:.3f}")
print()

# Dự đoán cho hai điểm mới
moi = np.array([[3.0, 3.0], [5.0, 4.5]])
for diem, f, lop in zip(moi, svm.decision_function(moi), svm.predict(moi)):
    print(f"Diem ({diem[0]}, {diem[1]}): f(x) = {f:+.3f}, doan lop {lop}")

import numpy as np
import pandas as pd
from sklearn.metrics import accuracy_score
from sklearn.model_selection import train_test_split
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.svm import SVC

df = pd.read_csv("sinh_vien.csv")
X = df[["gio_on", "diem_giua_ky"]]
y = df["qua_mon"]
X_tr, X_te, y_tr, y_te = train_test_split(
    X, y, test_size=0.25, random_state=17, stratify=y
)

print("Tap hoc co", len(X_tr), "ban")
print("      C   so vecto HT   do rong le   tap hoc   tap kiem tra")
for C in [0.01, 0.1, 1, 10, 100]:
    mh = make_pipeline(StandardScaler(),
                       SVC(kernel="linear", C=C))
    mh.fit(X_tr, y_tr)
    svm = mh[-1]  # bước cuối của pipeline là SVM
    le = 2 / np.linalg.norm(svm.coef_[0])
    a_hoc = accuracy_score(y_tr, mh.predict(X_tr))
    a_kt = accuracy_score(y_te, mh.predict(X_te))
    print(f"  {C:6} {len(svm.support_):12d} {le:12.2f}"
          f" {a_hoc:9.4f} {a_kt:13.4f}")
print()

